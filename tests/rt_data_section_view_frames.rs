/// The class gate and a truncated body refuse gracefully.
#[test]
fn the_gates_refuse() {
    let r = record("AECC_GRAPH_PROFILE_VIEW", SPO_KEYED, 1032, 360);
    assert_eq!(r.section_view_frame(), None);
    // Cut the record to a quarter (the class body runs to ~bit 6034; a
    // quarter record's main stream ends at ~bit 2848, inside the class
    // head): the reader runs out of bits and refuses gracefully.
    let r = record("AECC_GRAPH_SECTION_VIEW", &SPO_KEYED[..SPO_KEYED.len() / 4], 1032, 360);
    assert_eq!(r.section_view_frame(), None);
}

/// The whole denominator: every one of Sections-Project-Objects.dwg's 19
/// section views reads its frame, and the ranges carry the swath widths
/// the sample lines show (300 left, 300 right).
#[test]
fn every_project_objects_view_reads_its_frame() {
    let Some(dir) = std::env::var_os("ACADRUST_CIVIL_TUTORIALS_DIR") else { return };
    let path = std::path::Path::new(&dir).join("Sections-Project-Objects.dwg");
    if !path.exists() {
        return;
    }
    let doc: CadDocument = DwgReader::from_file(&path).unwrap().read().unwrap();
    let mut frames = 0;
    for e in doc.entities() {
        if let EntityType::Extended(x) = e {
            if let ExtendedEntityData::Arch(a) = &x.data {
                if a.dxf_name != "AECC_GRAPH_SECTION_VIEW" {
                    continue;
                }
                let f = a.section_view_frame().unwrap_or_else(|| panic!("view {:#x} refuses", x.common.handle.value()));
                assert_eq!((f.offset_min, f.offset_max), (-300.0, 300.0));
                assert_eq!(f.vertical_scale, 1.0);
                frames += 1;
            }
        }
    }
    assert_eq!(frames, 19);
    let _ = Handle::new(0);
}
