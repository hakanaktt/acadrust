fn record(dxf: &str, hex: &str, code: i16, handle_bits: i64) -> ArchEntityData {
    let bytes: Vec<u8> = (0..hex.len() / 2)
        .map(|i| u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).expect("hex"))
        .collect();
    ArchEntityData {
        dxf_name: dxf.to_string(),
        cpp_class_name: "AeccDbGraphCrossSection".to_string(),
        kind: ArchKind::Other,
        profiles: Vec::new(),
        dwg_type_code: code,
        dwg_handle_bits: handle_bits,
        dwg_source_version: Some(DxfVersion::AC1032),
        raw_dwg_data: Some(bytes),
        raw_dxf_codes: None,
        fields: Vec::new(),
        preview: Vec::new(),
    }
}

/// The keyed-head project-objects view: its band gap is 1/48, its band
/// style id 449, and the frame reads (origin at offset 0 of elevation 580,
/// offsets -300..300, elevations 580..690, scale 1).
#[test]
fn the_keyed_head_view_s_frame_reads() {
    let r = record("AECC_GRAPH_SECTION_VIEW", SPO_KEYED, 1032, 360);
    assert_eq!(
        r.section_view_frame(),
        Some(SectionViewFrame {
            origin: acadrust::types::Vector2::new(7962.002992327289, 2753.4147138894978),
            offset_min: -300.0,
            offset_max: 300.0,
            elevation_min: 580.0,
            elevation_max: 690.0,
            vertical_scale: 1.0,
        })
    );
}

