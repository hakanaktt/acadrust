//! Section view frames (`AECC_GRAPH_SECTION_VIEW`): the band record's
//! grammar admits both forms on file. The band opens with its gap to the
//! view — a `BD`, 0 in most samples (where it reads like `BL 0`) and 1/48
//! in the project-objects views — followed by two words (a band style id:
//! 257 in the data band's views, 449 in the project objects'), a word, a
//! `BD`, the band's index and its two label offsets. Records pinned bit
//! for bit from Civil 3D 2027 (2026-11-28): the two head forms of
//! Sections-Project-Objects.dwg (19 views, the pilot gap's whole
//! denominator — the only section views in the corpus that refused on the
//! old grammar) and one zero-gap view of Sections-Data-Band.dwg (the form
//! the old grammar already admitted, pinned so it stays admitted).

